"""Independent real-model layout oracles. Evaluation only, no quality tuning.

Three distinct checks: exact compact-source construction, original-layout
masked attention, and no-eviction padding controls for finite-precision drift.
Neither reference constructs masks using the production adapter mask builder.
"""

from __future__ import annotations

from contextlib import contextmanager


def independent_state(adapter, original, positions, *, original_layout=False, padding=0):
    import torch

    from mosaickv.adapters.huggingface.types import CacheLayerSnapshot, CacheSnapshot, DecodeState

    native = adapter.extract_past_key_values(original.past_key_values, clone=False)
    source_layers, source_kind = adapter._legacy_layers(native)
    capacity = (
        original.active_cache_length
        if original_layout
        else max(len(ids) for ids in positions.values())
    ) + padding
    layers = []
    valid = []
    for layer, (key, value) in enumerate(source_layers):
        if (
            key.ndim != 4
            or adapter._cache_sequence_dimension(key) != 2
            or key.shape != value.shape
            or key.shape[0] != 1
        ):
            raise NotImplementedError(
                "independent oracle supports batch-one B,H,N,D with equal K/V widths"
            )
        k = torch.zeros(
            (1, key.shape[1], capacity, key.shape[3]), device=key.device, dtype=key.dtype
        )
        v = torch.zeros_like(k)
        mask = torch.zeros((key.shape[1], capacity), device=key.device, dtype=torch.bool)
        if original_layout:
            k[:, :, : key.shape[2]] = key
            v[:, :, : value.shape[2]] = value
        for head in range(key.shape[1]):
            ids = tuple(positions[(layer, head)])
            if (
                not ids
                or ids != tuple(sorted(set(ids)))
                or min(ids) < 0
                or max(ids) >= key.shape[2]
            ):
                raise ValueError("invalid independent retained positions")
            if original_layout:
                mask[head, list(ids)] = True
            else:
                # Independent scalar-head gather, deliberately not the packer's
                # batched source-slot tables or validity masks.
                k[:, head, : len(ids)] = key[:, head, list(ids)]
                v[:, head, : len(ids)] = value[:, head, list(ids)]
                mask[head, : len(ids)] = True
        layers.append(CacheLayerSnapshot(k, v, 2))
        valid.append(mask)
    model_state = {k: v for k, v in original.model_state.items() if not k.startswith("mosaickv_")}
    # Permit compressed logical positions; actual masking is independently
    # supplied below, not generated by _packed_decode_masks.
    model_state.update(mosaickv_packed_all_valid=True, mosaickv_cache_all_valid=True)
    cache = CacheSnapshot(
        tuple(layers),
        type(native),
        source_kind,
        capacity,
        adapter.capabilities.cached_key_state,
    )
    state = DecodeState(
        adapter.inject_past_key_values(cache),
        torch.ones((1, capacity), dtype=original.attention_mask.dtype, device=layers[0].key.device),
        capacity,
        original.logical_sequence_length,
        original.next_decode_position,
        original.modality_map,
        model_state,
    )
    return state, tuple(valid)


@contextmanager
def independent_masks(adapter, state, prompt_masks):
    import torch

    handles = []
    for index, layer in enumerate(adapter._language_layers()):

        def override(module, args, kwargs, *, layer_index=index):
            if "attention_mask" not in kwargs:
                raise NotImplementedError("attention module does not expose mask keyword")
            original = prompt_masks[layer_index]
            heads = int(module.config.num_attention_heads)
            kv_heads = int(original.shape[0])
            if heads % kv_heads:
                raise ValueError("invalid query-to-KV ownership")
            length = state.active_cache_length + 1
            valid = torch.ones((kv_heads, length), dtype=torch.bool, device=original.device)
            valid[:, : original.shape[1]] = original
            valid = valid.repeat_interleave(heads // kv_heads, dim=0)
            additive = torch.zeros(
                (1, heads, 1, length), dtype=next(module.parameters()).dtype, device=original.device
            )
            additive.masked_fill_(~valid[None, :, None, :], -torch.inf)
            kwargs["attention_mask"] = additive
            return args, kwargs

        handles.append(layer.self_attn.register_forward_pre_hook(override, with_kwargs=True))
    try:
        yield
    finally:
        for handle in handles:
            handle.remove()


def _step(adapter, token, state, masks=None):
    if masks is None:
        return adapter.decode_one_token(
            token, state, capture_queries=False, capture_attentions=False
        )
    with independent_masks(adapter, state, masks):
        return adapter.decode_one_token(
            token, state, capture_queries=False, capture_attentions=False
        )


def unpruned_padding_control(adapter, original, first_token, *, steps=16):
    """Identical evidence/logical positions; only physical trailing holes differ."""
    import torch

    source = adapter._legacy_layers(original.past_key_values)[0]
    all_positions = {
        (layer, head): tuple(range(k.shape[2]))
        for layer, (k, _v) in enumerate(source)
        for head in range(k.shape[1])
    }
    # No-eviction control is independent of the compressed method's selections
    # and continuations. Follow FullKV's own greedy tokens in both layouts.
    full, full_masks = independent_state(adapter, original, all_positions, original_layout=True)
    padded, padded_masks = independent_state(
        adapter,
        original,
        all_positions,
        original_layout=True,
        padding=max(1, original.active_cache_length // 3),
    )
    token = torch.tensor([[int(first_token)]], device=adapter.device, dtype=torch.long)
    padding_errors = []
    for _ in range(steps):
        a = _step(adapter, token, full, full_masks)
        b = _step(adapter, token, padded, padded_masks)
        if not bool(torch.isfinite(a.logits).all() and torch.isfinite(b.logits).all()):
            raise AssertionError("non-finite logits in unpruned padding control")
        absolute = float((a.logits.float() - b.logits.float()).abs().max().item())
        norm = max(1.0, float(a.logits.float().abs().max().item()))
        padding_errors.append(dict(absolute=absolute, normalized_linf=absolute / norm))
        token = a.next_token_id
        if full.next_decode_position != padded.next_decode_position:
            raise AssertionError("padding control changed logical next position")
    return padding_errors


def validate_independent_layout(adapter, original, candidate, positions, token_ids, *, steps=16):
    import torch

    dtype = adapter._legacy_layers(original.past_key_values)[0][0][0].dtype
    eps = 8 * torch.finfo(dtype).eps
    padding_errors = unpruned_padding_control(adapter, original, token_ids[0], steps=steps)
    control_pass = all(item["normalized_linf"] <= eps for item in padding_errors)
    compact, compact_masks = independent_state(adapter, original, positions)
    masked, masked_masks = independent_state(adapter, original, positions, original_layout=True)
    for (ck, cv), (rk, rv) in zip(
        adapter._legacy_layers(candidate.past_key_values)[0],
        adapter._legacy_layers(compact.past_key_values)[0],
        strict=True,
    ):
        if (
            ck.dtype != rk.dtype
            or ck.device != rk.device
            or not torch.equal(ck, rk)
            or not torch.equal(cv, rv)
        ):
            raise AssertionError("production packing differs from independent source gather")
    measurements = []
    for index in range(steps):
        token = torch.tensor([[token_ids[index]]], device=adapter.device, dtype=torch.long)
        actual = _step(adapter, token, candidate)
        oracle = _step(adapter, token, compact, compact_masks)
        original_output = _step(adapter, token, masked, masked_masks)
        exact_error = float((actual.logits.float() - oracle.logits.float()).abs().max().item())
        mask_error = float(
            (actual.logits.float() - original_output.logits.float()).abs().max().item()
        )
        norm = max(1.0, float(original_output.logits.float().abs().max().item()))
        measurements.append(
            dict(
                step=index,
                compact_max_absolute=exact_error,
                masked_max_absolute=mask_error,
                masked_normalized_linf=mask_error / norm,
                compact_greedy_equal=bool(torch.equal(actual.next_token_id, oracle.next_token_id)),
                masked_greedy_equal=bool(
                    torch.equal(actual.next_token_id, original_output.next_token_id)
                ),
                legacy_elementwise_8epsilon_passed=bool(
                    torch.allclose(actual.logits, original_output.logits, atol=eps, rtol=eps)
                ),
            )
        )
        if (
            actual.state.next_decode_position != oracle.state.next_decode_position
            or actual.state.next_decode_position != original_output.state.next_decode_position
        ):
            raise AssertionError("independent reference changed original logical decode positions")
    free, free_masks = independent_state(adapter, original, positions, original_layout=True)
    free_tokens = []
    token = torch.tensor([[token_ids[0]]], device=adapter.device, dtype=torch.long)
    for _ in range(steps):
        output = _step(adapter, token, free, free_masks)
        token = output.next_token_id
        free_tokens.append(int(token.item()))
    strict = all(
        item["compact_max_absolute"] <= 1e-4 and item["compact_greedy_equal"]
        for item in measurements
    )
    normalized = all(item["masked_normalized_linf"] <= eps for item in measurements)
    return dict(
        status="passed" if control_pass and strict and normalized else "failed",
        numerical_contract="independent_compact_strict_plus_unpruned_controlled_normwise_FP16_v2",
        forced_steps=steps,
        source_entries_bitwise=True,
        independent_mask_builder=True,
        compact_absolute_tolerance=1e-4,
        original_layout_normwise_tolerance=eps,
        retention_one_absolute_tolerance_unchanged=1e-4,
        unpruned_padding_control=padding_errors,
        unpruned_control_passed=control_pass,
        independent_compact_passed=strict,
        original_masked_normwise_passed=normalized,
        legacy_elementwise_contract_passed=all(
            item["legacy_elementwise_8epsilon_passed"] for item in measurements
        ),
        legacy_failures_preserved_not_reclassified=True,
        per_step=measurements,
        masked_source_free_running_tokens=free_tokens,
        packed_free_running_tokens=list(token_ids[1 : steps + 1]),
        free_running_token_agreement=sum(
            a == b for a, b in zip(free_tokens, token_ids[1 : steps + 1], strict=True)
        )
        / steps,
        first_prefill_token_excluded_from_agreement=True,
    )
